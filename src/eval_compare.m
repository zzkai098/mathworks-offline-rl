%% Offline-RL GBWM — end-to-end eval narrative (Part A evolution / B diagnosis / C backtest)
% Single comparison surface for the deliverable. Authored as a cell-structured .m so it
% converts cleanly to a Live Script (.mlx): open in MATLAB, Save As -> .mlx.
%
%   Part A  Model evolution on real data (6-D DQN line) — REPLAYED from the saved
%           TrainedAgent.mat of each stage (gross, cost=0; full metric set). Shows how
%           raw macro-DQN -> regime reward -> drawdown penalty -> 6.1 (regime-gated)
%           traded off Sharpe vs tail, ending in 6.1 = first regime-conditional but
%           still across-seed-unstable version.
%   Part B  Diagnosis (the headline): 6.1's Q diverges; a Polyak + LR fix bounds it;
%           IQL removes the OOD-max term structurally. Imports the figures already
%           generated by week9c/9d + week10 matrix.
%   Part C  Final cost-aware backtest, split into C1 (SINGLE shipped agent, seed 1000)
%           and C2 (N=10 ENSEMBLE), each = tuned-DQN & IQL vs baseline panel
%           (behavior-random / 1-N / MVO / 60-40) on ONE chained test path, with
%           block-bootstrap Sharpe CI + Deflated Sharpe. Two tables + two equity figures
%           (eval_partC1_single_equity.png / eval_partC2_ensemble_equity.png).
%
% Run from project root. Needs experiments/models/{dqn,iql}_seed_*.mat (train_*_seeds.sh)
% and experiments/figures/week9c/9d/10 PNGs.
clear; clc;
addpath("src"); addpath(fullfile("src","utils"));

%% ===== Part A — evolution of the 6-D DQN line (REPLAYED from saved agents, gross) =====
% Loads each stage's 5 trained agents from experiments/logs/archive/<stage>/seed_*/
% TrainedAgent.mat and replays them GREEDILY through the hold-out windows (gross, cost=0,
% matching how the reward-engineering evolution was originally compared). Each stage uses
% ITS OWN training basis (frontier + macro normalizer differ by train window) so every
% agent sees the state distribution it was trained on. This actually runs the historical
% agents (not a hard-coded table). Full metric set: success, Sharpe, across-seed std,
% MaxDD (mean & P90), worst Sharpe, terminal P10/mean.
evoSeeds = 1000:1000:5000;
% {label, logdir, pricesFile, macroFile, trainingRange}
evo = {
  'v3: raw 6-D macro',          'week4_macro_state_v3',   'data/prices_train.csv',          'data/macro_train.csv',          2515
  '+ regime reward (v2)',       'week5_regime_reward_v2', 'data/prices_train.csv',          'data/macro_train.csv',          2515
  '+ drawdown penalty (PlanC)', 'week5_drawdown_penalty', 'data/prices_train.csv',          'data/macro_train.csv',          2515
  '6.1: regime-gated',          'week6_1_regime_gated',   'data/prices_train_extended.csv', 'data/macro_train_extended.csv', 3020
};
nEvo = size(evo,1);
Astage=strings(nEvo,1); Asucc=nan(nEvo,1); Ash=nan(nEvo,1); Astd=nan(nEvo,1);
Amdd=nan(nEvo,1); Ap90=nan(nEvo,1); Aworst=nan(nEvo,1); Ap10=nan(nEvo,1); Amt=nan(nEvo,1);
for e = 1:nEvo
    bA = buildEvalBasis(evo{e,3}, evo{e,4}, evo{e,5}, 15);   % per-version basis
    seedSharpe = nan(numel(evoSeeds),1);  seedSucc = nan(numel(evoSeeds),1);
    poolDD=[]; poolSh=[]; poolTw=[];
    for si = 1:numel(evoSeeds)
        ap = sprintf("experiments/logs/archive/%s/seed_%d/TrainedAgent.mat", evo{e,2}, evoSeeds(si));
        if ~isfile(ap); warning("missing %s — skipped", ap); continue; end
        La = load(ap,"agent");  cr = getCritic(La.agent);
        [G,T] = replayPolicy(@(o) argmaxIdx(getValue(cr,{o})), bA);
        m = windowMetrics(G, T, 0, bA, false);              % cost = 0 (gross)
        seedSharpe(si) = m.meanSharpe;  seedSucc(si) = m.success;
        poolDD=[poolDD; m.perWin.maxDD]; poolSh=[poolSh; m.perWin.sharpe]; poolTw=[poolTw; m.perWin.termW]; %#ok<AGROW>
    end
    assert(sum(~isnan(seedSharpe))==numel(evoSeeds), ...
        'Part A: only %d/%d seeds loaded for %s', sum(~isnan(seedSharpe)), numel(evoSeeds), evo{e,1});
    poolDD=poolDD(~isnan(poolDD)); poolSh=poolSh(~isnan(poolSh)); poolTw=poolTw(~isnan(poolTw));
    Astage(e)=evo{e,1};
    Ash(e)=mean(seedSharpe,'omitnan');  Astd(e)=std(seedSharpe,'omitnan');  Asucc(e)=mean(seedSucc,'omitnan');
    Amdd(e)=100*mean(poolDD);  Ap90(e)=100*prctile(poolDD,90);  Aworst(e)=min(poolSh);
    Ap10(e)=prctile(poolTw,10);  Amt(e)=mean(poolTw);
end
Aevo = table(Astage,Asucc,Ash,Astd,Amdd,Ap90,Aworst,Ap10,Amt, ...
    'VariableNames',{'stage','SuccRate','MeanSharpe','AcrossSeedStd','MeanMaxDD_pct','MaxDD_P90_pct','WorstSharpe','TermP10','MeanTerm'});
disp("=== Part A — 6-D DQN evolution (replayed from saved agents; gross cost=0; 5 seeds) ===");
disp(Aevo);
fprintf(['NOTE: Part A is GROSS (cost=0), per-window Sharpe (window-reset), 5 seeds each,\n' ...
         '      replayed from the historical TrainedAgent.mat, ending at 6.1 (pre-fix). Part C\n' ...
         '      is the cost-aware CHAINED deliverable eval on the shipped tuned-DQN — different\n' ...
         '      protocol, not directly comparable.\n']);

fA = figure('Name','Part A — evolution','Position',[100 100 1000 400]);
tiledlayout(1,2,'TileSpacing','compact');
nexttile;
yyaxis left;  plot(1:nEvo, Ash,'-o','LineWidth',1.8);  ylabel('Mean Sharpe');
yyaxis right; plot(1:nEvo, Astd,'-s','LineWidth',1.4); ylabel('across-seed std');
xticks(1:nEvo); xticklabels(Astage); xtickangle(20); grid on; title('Sharpe + reproducibility');
nexttile; hold on; grid on;
plot(1:nEvo, Ap90,'-o','LineWidth',1.8,'DisplayName','MaxDD P90 (%)');
plot(1:nEvo,-Aworst,'-s','LineWidth',1.8,'DisplayName','-Worst Sharpe');
xticks(1:nEvo); xticklabels(Astage); xtickangle(20); legend('Location','northwest');
title('Tail risk across the evolution');
if ~isfolder('experiments/figures'); mkdir('experiments/figures'); end
exportgraphics(fA, 'experiments/figures/eval_partA_evolution.png', 'Resolution', 150);

%% ===== Part B — diagnosis (redrawn live from the logged CSVs) =====
% Redrawn from experiments/logs/*.csv each run (native figures, not imported PNGs), so
% they are guaranteed to match the recorded diagnosis. The standalone week9c_plot /
% week9d_plot / week10_matrix_plot scripts stay the canonical PNG generators for the
% report; this reproduces them inline for the Live Script.
disp("=== Part B — diagnosis (redrawn from CSV) ===");
MEg = [50 100 200 400];  bSeeds = [1000 2000 3000];

% --- B1: 6.1 DQN Q diverges + eval never stabilizes (week9c) ---
f9c = 'experiments/logs/week9c_results.csv';
if isfile(f9c)
    T = readtable(f9c); [~,ia] = unique(T(:,{'seed','ME'}),'rows','stable'); T = T(ia,:);
    sd = unique(T.seed); cB = lines(numel(sd));
    fB1 = figure('Name','Part B1 — 6.1 Q diverges','Position',[120 120 1100 430]);
    subplot(1,2,1); hold on; grid on;
    for i=1:numel(sd); s=sortrows(T(T.seed==sd(i),:),'ME');
        semilogy(s.ME,s.qGlobal,'-o','LineWidth',2,'Color',cB(i,:),'DisplayName',sprintf('seed %d',sd(i))); end
    set(gca,'YScale','log'); xlabel('MaxEpochs'); ylabel('val mean max_a Q  [log]');
    title('6.1 DQN Q DIVERGES with training'); legend('Location','northwest');
    subplot(1,2,2); hold on; grid on;
    for i=1:numel(sd); s=sortrows(T(T.seed==sd(i),:),'ME');
        plot(s.ME,s.evalSharpe,'-o','LineWidth',2,'Color',cB(i,:),'DisplayName',sprintf('seed %d',sd(i))); end
    xlabel('MaxEpochs'); ylabel('hold-out eval Sharpe'); title('Eval never stabilizes (across-seed spread)'); legend('Location','best');
else; fprintf('  (missing) %s\n', f9c); end

% --- B2: target-update + LR fix (week9c vs week9d vs matrix full-fix) ---
f9d = 'experiments/logs/week9d_results.csv';
if isfile(f9c) && isfile(f9d)
    C = readtable(f9c); [~,ic]=unique(C(:,{'seed','ME'}),'rows','stable'); C=C(ic,:);
    D = readtable(f9d); [~,idd]=unique(D(:,{'tsf','seed','ME'}),'rows','stable'); D=D(idd,:);
    fB2 = figure('Name','Part B2 — the fix','Position',[120 120 1150 450]);
    subplot(1,2,1); hold on; grid on; hC=[];hD=[];hM=[];
    for s=bSeeds
        c=sortrows(C(C.seed==s,:),'ME'); hC=semilogy(c.ME,c.qGlobal,'--o','Color',[0.85 0.2 0.2],'LineWidth',1.5);
        d=sortrows(D(D.tsf==1e-3 & D.seed==s,:),'ME'); hD=semilogy(d.ME,d.qGlobal,'-o','Color',[0.1 0.5 0.85],'LineWidth',1.6);
        qm=nan(1,4); for k=1:4; fm=sprintf('experiments/logs/matrix/dqn_s%d_me%d.csv',s,MEg(k)); if isfile(fm); r=readmatrix(fm); qm(k)=r(5); end; end
        hM=semilogy(MEg,qm,'-s','Color',[0.1 0.6 0.2],'LineWidth',2.2);
    end
    set(gca,'YScale','log'); yline(1.2,':k','economic ceiling ~1.2');
    xlabel('MaxEpochs'); ylabel('val mean max_a Q  [log]'); title('Target update + LR: partial vs full fix');
    legend([hC hD hM],{'periodic-4 (6.1: diverges)','Polyak \tau=1e-3 (residual@400)','+ LR 1e-4 (full fix)'},'Location','northwest');
    subplot(1,2,2); hold on; grid on;
    qC=nan(4,3); qD=nan(4,3);
    for i=1:4; for j=1:3
        vc=C.qGlobal(C.seed==bSeeds(j)&C.ME==MEg(i)); if ~isempty(vc); qC(i,j)=vc(1); end
        vd=D.qGlobal(D.tsf==1e-3&D.seed==bSeeds(j)&D.ME==MEg(i)); if ~isempty(vd); qD(i,j)=vd(1); end
    end; end
    plot(MEg,max(qC,[],2)-min(qC,[],2),'--s','Color',[0.85 0.2 0.2],'LineWidth',1.5,'DisplayName','6.1 across-seed Q spread');
    plot(MEg,max(qD,[],2)-min(qD,[],2),'-s','Color',[0.1 0.5 0.85],'LineWidth',2,'DisplayName','\tau=1e-3 spread');
    set(gca,'YScale','log'); xlabel('MaxEpochs'); ylabel('across-seed Q spread  [log]'); title('Across-seed variance collapses'); legend('Location','northwest');
else; fprintf('  (missing) %s or %s\n', f9c, f9d); end

% --- B3: tuned-DQN vs IQL final matrix (both bounded, equivalent) ---
if isfile('experiments/logs/matrix/dqn_s1000_me100.csv')
    qD=nan(4,3); shD=nan(4,3); qI=nan(4,3); shI=nan(4,3);
    for i=1:4; for j=1:3
        fd=sprintf('experiments/logs/matrix/dqn_s%d_me%d.csv',bSeeds(j),MEg(i)); if isfile(fd); r=readmatrix(fd); qD(i,j)=r(5); shD(i,j)=r(12); end
        fi=sprintf('experiments/logs/matrix/iql_s%d_me%d.csv',bSeeds(j),MEg(i)); if isfile(fi); r=readmatrix(fi); qI(i,j)=r(6); shI(i,j)=r(13); end
    end; end
    fB3 = figure('Name','Part B3 — DQN vs IQL','Position',[120 120 1300 420]);
    subplot(1,3,1); hold on; grid on; ylim([0 2]);
    for j=1:3; plot(MEg,qD(:,j),'--o','Color',[0.85 0.3 0.1],'LineWidth',1.3); plot(MEg,qI(:,j),'-o','Color',[0.1 0.5 0.85],'LineWidth',1.7); end
    yline(1.14,':k','ceiling'); xlabel('epochs'); ylabel('val mean max_a Q'); title('Both BOUNDED (DQN --, IQL -)');
    subplot(1,3,2); hold on; grid on;
    plot(MEg,std(shD,0,2),'--s','Color',[0.85 0.3 0.1],'LineWidth',2,'DisplayName','tuned-DQN');
    plot(MEg,std(shI,0,2),'-s','Color',[0.1 0.5 0.85],'LineWidth',2,'DisplayName','IQL');
    xlabel('epochs'); ylabel('across-seed eval-Sharpe std'); title('Deciding metric: reproducibility'); legend('Location','best');
    subplot(1,3,3); hold on; grid on;
    errorbar(MEg,mean(shD,2),std(shD,0,2),'--s','Color',[0.85 0.3 0.1],'LineWidth',1.5,'DisplayName','tuned-DQN');
    errorbar(MEg,mean(shI,2),std(shI,0,2),'-s','Color',[0.1 0.5 0.85],'LineWidth',1.5,'DisplayName','IQL');
    xlabel('epochs'); ylabel('mean eval Sharpe (±seed std)'); title('Mean eval (overlapping)'); legend('Location','best');
