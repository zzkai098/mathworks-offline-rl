% Headline: 6.1's across-seed instability was Q-divergence (offline deadly triad),
% not seed luck. Two mis-set hyperparameters (fast target + high LR) caused it; the
% fix = tuned-DQN. IQL removes the diverging OOD-max term by construction -> its
% equivalent policy CONFIRMS the fix is complete and the ceiling is the data/regime.

%% ===== Part C — final cost-aware backtest (C1 single-seed + C2 ensemble) =====
basis   = buildEvalBasis();          % extended train 2010-2021, 15 actions
costBps = 10;                        % primary net cost
ensSeeds = 1000:1000:10000;          % N=10 ensemble members
Wf = basis.W_frontier;  nA = basis.numActions;

% --- load agents ---
dqnCritics = cell(numel(ensSeeds),1);  iqlNets = cell(numel(ensSeeds),1);
for i = 1:numel(ensSeeds)
    L = load(sprintf("experiments/models/dqn_seed_%d.mat", ensSeeds(i)), "FA");
    assert(contains(L.FA.meta.learner,"tuned-DQN"), "wrong-config DQN seed %d", ensSeeds(i));
    dqnCritics{i} = getCritic(L.FA.agent);
    Li = load(sprintf("experiments/models/iql_seed_%d.mat", ensSeeds(i)), "FI");
    assert(contains(Li.FI.meta.learner,"IQL"), "wrong-config IQL seed %d", ensSeeds(i));
    iqlNets{i}    = Li.FI.qNet;
end

% shared baseline roster (seed-independent) — appears in both C1 and C2 for reference
baseRoster = {
  'behavior(random)', @(o) Wf(:, randi(nA))
  '1/N',              @(o) basis.w1N
  'MVO',              @(o) basis.wMVO
  '60/40',            @(o) basis.w6040
};

% ---- Part C1: SINGLE shipped agent (seed 1000) ----
c1 = [ {'tuned-DQN (seed1000)', @(o) argmaxIdx(getValue(dqnCritics{1},{o}))
        'IQL (seed1000)',       @(o) argmaxIdx(iqlQ(iqlNets{1},o))} ; baseRoster ];
[C1tab, c1curves, c1nm] = runRoster(c1, basis, costBps);
fprintf("\n=== Part C1 — SINGLE agent (shipped seed 1000) @ %d bp (chained) ===\n", costBps);
disp(C1tab);
fprintf("NOTE: seed 1000 is ONE favorable realized path, not a cross-seed-robust result.\n");
plotEquity(c1curves, c1nm, basis, ...
    sprintf('Part C1 — single agent (seed 1000) vs baselines (net %d bp)', costBps), ...
    'experiments/figures/eval_partC1_single_equity.png');

% ---- Part C2: N=10 ENSEMBLE ----
c2 = [ {'tuned-DQN (N=10 ens)', @(o) argmaxIdx(ensSumDQN(dqnCritics,o))
        'IQL (N=10 ens)',       @(o) argmaxIdx(ensSumIQL(iqlNets,o))} ; baseRoster ];
[C2tab, c2curves, c2nm] = runRoster(c2, basis, costBps);
fprintf("\n=== Part C2 — N=10 ENSEMBLE @ %d bp (chained) ===\n", costBps);
disp(C2tab);
fprintf(['NOTE: ensemble TotRet is sensitive to the ensemble size N (this run: N=10 = %+.1f%%; an\n' ...
         '      earlier sweep gave materially different, even negative, totals at N=5 and N=20) —\n' ...
         '      N=10 is one pick, not a robust edge. Chaining also leaves the 29 window-boundary\n' ...
         '      rebalances uncharged (favors the portfolio-switching agents).\n'], C2tab.TotRet_pct(1));
plotEquity(c2curves, c2nm, basis, ...
    sprintf('Part C2 — N=10 ensemble vs baselines (net %d bp)', costBps), ...
    'experiments/figures/eval_partC2_ensemble_equity.png');

% Honest read: in BOTH C1 and C2 the chained-Sharpe 95%% CIs overlap and include 0 -> the
% agents are not statistically distinguishable from 60/40 (read the winner off the tables,
% don't assume); DSR near 0 (survives no multiple-testing haircut). The contribution is the
% Part-B diagnosis, not a return edge.

%% ===== local helpers =====
function a = argmaxIdx(q)
    q = q(:); [~,a] = max(q);
end
function q = iqlQ(net, o)
    q = extractdata(forward(net, dlarray(o,'CB')));
end
function q = ensSumDQN(critics, o)
    q = 0; for i = 1:numel(critics); v = getValue(critics{i},{o}); q = q + v(:); end
end
function q = ensSumIQL(nets, o)
    q = 0; for i = 1:numel(nets); q = q + iqlQ(nets{i}, o); end
end
function [tab, curves, nm] = runRoster(strat, basis, costBps)
    n = size(strat,1);
    nm=strings(n,1); TotRet=nan(n,1); ChSharpe=nan(n,1); ciLo=nan(n,1); ciHi=nan(n,1);
    DSR=nan(n,1); DDp90=nan(n,1); TermP10=nan(n,1); Succ=nan(n,1); curves=cell(n,1);
    for s = 1:n
        if strcmp(strat{s,1},'behavior(random)'); rng(20260730,'twister'); end   % reproducible random
        [G,T] = replayPolicy(strat{s,2}, basis);
        m = windowMetrics(G, T, costBps, basis, true);   % doStats -> CI + DSR (single path)
        nm(s)=strat{s,1}; TotRet(s)=100*m.totRet; ChSharpe(s)=m.chainedSharpe;
        ciLo(s)=m.ci(1); ciHi(s)=m.ci(2); DSR(s)=m.dsr; DDp90(s)=100*m.maxDDp90;
        TermP10(s)=m.termP10; Succ(s)=m.success; curves{s}=m.curve;
    end
    tab = table(nm, TotRet, ChSharpe, ciLo, ciHi, DSR, DDp90, TermP10, Succ, ...
        'VariableNames', {'strategy','TotRet_pct','ChainedSharpe','CI_lo','CI_hi','DSR','MaxDD_P90_pct','TermP10','Success'});
end
function plotEquity(curves, nm, basis, ttl, savePath)
    f = figure('Name',ttl,'Position',[100 100 1050 560]); hold on; grid on;
    n = numel(curves); cols = lines(n);
    baseSet = {'behavior(random)','1/N','MVO','60/40'};
    for s = 1:n
        isB = any(strcmp(nm(s), baseSet));  lw = 2.2; ls = '-'; if isB; lw = 1.4; ls = '--'; end
        plot(0:numel(curves{s})-1, curves{s}, ls, 'Color',cols(s,:), 'LineWidth',lw, 'DisplayName',nm(s));
    end
    yline(basis.initialWealth, ':k', 'start', 'HandleVisibility','off');
    xlabel('test trading day (30 chained 30-day windows)'); ylabel('cumulative wealth');
    title(ttl); subtitle('chained episodic-reset (boundary rebalances uncharged)');
    legend('Location','northwest');
    if ~isfolder('experiments/figures'); mkdir('experiments/figures'); end
    exportgraphics(f, savePath, 'Resolution', 150);
end
